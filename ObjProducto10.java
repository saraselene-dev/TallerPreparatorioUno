public class ObjProducto10 {
    private String Nombre;
    private boolean EnOferta;
    public ObjProducto10() {
    }
    public ObjProducto10(String nombre, boolean enOferta) {
        Nombre = nombre;
        EnOferta = enOferta;
    }
    public String getNombre() {
        return Nombre;
    }
    public void setNombre(String nombre) {
        Nombre = nombre;
    }
    public boolean isEnOferta() {
        return EnOferta;
    }
    public void setEnOferta(boolean enOferta) {
        EnOferta = enOferta;
    }

}
