public class ObjAsiento4 {
    private int Numero;
    private int Fila;
    private double Precio;

    public ObjAsiento4() {
    }

    public ObjAsiento4(int numero, int fila, double precio) {
        Numero = numero;
        Fila = fila;
        Precio = precio;
    }

    public int getNumero() {
        return Numero;
    }

    public void setNumero(int numero) {
        Numero = numero;
    }

    public int getFila() {
        return Fila;
    }

    public void setFila(int fila) {
        Fila = fila;
    }

    public double getPrecio() {
        return Precio;
    }

    public void setPrecio(double precio) {
        Precio = precio;
    }

}
